// Desktop
//
// SwiftUI port of the Flutter `desktop` package. See README.md for an
// overview of the available components and usage.
//
// All public symbols are exposed from this module:
//
// * Theme: ``Brightness``, ``ColorScheme``, ``ShadeColor``, ``BackgroundColor``,
//   ``PrimaryColor``, ``AnyPrimaryColor``, ``PrimaryColors``, ``ThemeData``,
//   ``Theme``.
// * App: ``DesktopApp``.
// * Input: ``DesktopButton``, ``Hyperlink``, ``DesktopCheckbox``,
//   ``ToggleSwitch``, ``DesktopRadio``, ``DesktopSlider``.
// * Status: ``LinearProgressIndicator``, ``CircularProgressIndicator``.
// * Dialogs: `View.desktopTooltip(_:)`.
// * Navigation: ``Tab``, ``TabItem``.
// * Text: ``DesktopTextField``.
// * Component: ``ComponentState``.
